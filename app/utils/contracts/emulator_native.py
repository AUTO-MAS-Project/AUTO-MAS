"""模拟器宿主能力与延迟装配的窗口操作。"""

from pathlib import Path
from typing import Protocol


class WindowVisibility(Protocol):
    def __call__(self, pid: int, name_port: str, visible: bool) -> int: ...


class EmulatorNativeAPI(Protocol):
    def shm_exists(self, port: int) -> bool: ...
    def cpu_cache_topology(self) -> bytes: ...
    def prepare_window_visibility(self) -> WindowVisibility: ...
    def vulkan_probe_path(self) -> Path | None: ...
