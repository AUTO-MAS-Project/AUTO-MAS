"""WindowAPI 的平台无关调用契约。"""

from typing import Protocol


class WindowAPI(Protocol):
    @property
    def WindowError(self) -> type[Exception]: ...

    def get_window_handles(self, pid: int) -> list[int]: ...

    def get_main_window_handle(
        self,
        pid: int,
        window_title: str | None = None,
        window_class_name: str | None = None,
    ) -> int | None: ...

    def is_visible(self, hwnd: int) -> bool: ...

    def is_window(self, hwnd: int) -> bool: ...

    def show_window(self, hwnd: int) -> bool: ...

    def hide_window(self, hwnd: int) -> bool: ...

    def minimize_window(self, hwnd: int) -> bool: ...

    def close_window(self, hwnd: int) -> bool: ...

    def activate_window(self, hwnd: int) -> bool: ...

    def get_dpi_scaling(self) -> float | None: ...

    def find_window_by_title(self, title: str) -> tuple[int, str] | None: ...

    def get_foreground_window(self) -> int: ...

    def get_window_text(self, hwnd: int) -> str: ...

    def get_window_rect(self, hwnd: int) -> tuple[int, int, int, int]: ...

    def is_minimized(self, hwnd: int) -> bool: ...

    def restore_window(self, hwnd: int) -> bool: ...

    def force_activate_window(self, hwnd: int) -> bool: ...

    def visible_owned_windows(self, owner: int) -> list[int]: ...

    def get_window_owner(self, hwnd: int) -> int: ...

    def get_window_class(self, hwnd: int) -> str: ...

    def set_window_visible_async(self, hwnd: int, *, visible: bool) -> None: ...

    def find_window_by_process(self, title: str, process_name: str) -> int | None: ...
