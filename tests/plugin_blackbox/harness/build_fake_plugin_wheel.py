"""Sample plugin wheel builder for fake host tests.

Generates a minimal wheel with a controllable `Plugin` class. The
class is parameterized by a small JSON config so we can drive
pass / fail / leak / reload scenarios from a single test entry.

NOTE: The generated wheel is built in the scratch plugins_dir passed
by the harness. It does NOT touch the formal plugins/wheels/ tree.
"""
